def translate(key, lang=DEFAULT_LANGUAGE, **kwargs):
    """Look up `key` in `lang`, falling back to English, then to the key
    itself if it is missing everywhere (so a typo never crashes a page)."""
    lang = lang if lang in TRANSLATIONS else DEFAULT_LANGUAGE
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text
